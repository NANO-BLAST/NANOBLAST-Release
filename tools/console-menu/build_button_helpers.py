"""Build word-aligned SNES helper tiles from the exact embedded background."""
from pathlib import Path
import re,struct,zlib,json,argparse
r=Path(__file__).resolve().parents[2]
s=(r/'firmware/ui/background_seed.inc').read_text();v=re.search(r'static const uint8_t background_seed\[\]=\{(.*?)\};',s,re.S)[1];z=bytes(int(x,16) for x in re.findall(r'0x([0-9a-fA-F]{2})',v));out=bytearray();i=16;size=struct.unpack_from('<I',z,8)[0]
while len(out)<size:
 flag=z[i];i+=1
 for bit in range(8):
  if len(out)==size:break
  if flag&(1<<bit):
   t=int.from_bytes(z[i:i+2],'little');i+=2
   for _ in range((t&15)+3):out.append(out[-((t>>4)+1)])
  else:out.append(z[i]);i+=1
assert len(out)==922400
base=bytes(out[800:]);pix=bytearray(base);pal=bytearray(out[32:800])
font=[int(x,16) for x in re.findall(r"8'h([0-9a-fA-F]{2})",(r/'tools/console-menu/font.vh').read_text())]
def put(x,y,c):pix[y*1280+x]=c
def text(x,y,t,c,scale=1):
 for n,ch in enumerate(t):
  for yy in range(8):
   for xx in range(8):
    if font[ord(ch)*8+yy]&(1<<xx):
     for dy in range(scale):
      for dx in range(scale):put(x+(n*8+xx)*scale+dx,y+yy*scale+dy,c)
for left,ch,fill,ink,glint in [(552,'A',240,242,245),(792,'B',241,243,246)]:
 for y in range(33):
  for x in range(33):
   rad=(x-16)**2+(y-16)**2
   if rad<=256:put(left+x,670+y,244 if rad>196 else fill)
   if 144<rad<175 and x<15 and y<15:put(left+x,670+y,glint)
 text(left+4,674,ch,ink,3)
# Grey slanted rubber Select/Start buttons, as on a SNES controller.
for left,label in [(264,'SELECT'),(344,'START')]:
 for y in range(24):
  shift=(23-y)//4
  for x in range(58):
   if (8<=x<50) or (x-8 if x<8 else x-49)**2+(y-11.5)**2<=132:
    put(left+x+shift,674+y,249 if y>20 else 248 if y<3 else 247)
 text(left+8 if label=='SELECT' else left+12,682,label,243)
text(332,681,'+',242)
for j,c in enumerate([0xb5b9c6,0xe5e6ed,0x444b5b]):pal[(247+j)*3:(248+j)*3]=c.to_bytes(3,'big')
layouts=[(552,36),(792,36),(264,80),(344,64)]
result='// Generated by tools/console-menu/build_button_helpers.py.\n'
for n,(left,width) in enumerate(layouts):
 for mode,source in [('plain',base),('visible',pix)]:
  data=b''.join(source[y*1280+left:y*1280+left+width] for y in range(670,703))
  result+=f'static const uint8_t helper_{n}_{mode}[]={{\n'+'\n'.join(','.join(f'0x{b:02x}' for b in data[j:j+24])+',' for j in range(0,len(data),24))+'\n};\n'
(r/'firmware/ui/background_helpers.inc').write_text(result)
# Internal preview of the exact indexed pixels, before text-layer labels.
parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,default=r/'artifacts/button-helpers');a=parser.parse_args().output;a.mkdir(parents=True,exist_ok=True)
(a/'helpers.json').write_text(json.dumps([dict(x=left,y=670,width=width,height=33,visible=list(b''.join(pix[y*1280+left:y*1280+left+width] for y in range(670,703)))) for left,width in layouts]))
rgb=b''.join(b'\0'+b''.join(pal[pix[y*1280+x]*3:pix[y*1280+x]*3+3] for x in range(1280)) for y in range(656,720))
def chunk(t,d):return struct.pack('>I',len(d))+t+d+struct.pack('>I',zlib.crc32(t+d))
(a/'preview.png').write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',1280,64,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(rgb))+chunk(b'IEND',b''))
