"""Generate an original, redistributable 8 KiB SMS board diagnostic, no assembler needed."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
rom=bytearray(8192);pc=0x100;labels={};refs=[]
def emit(*v):
 global pc
 rom[pc:pc+len(v)]=bytes(v);pc+=len(v)
def label(n):labels[n]=pc
def jump(op,n):
 emit(op,0,0);refs.append((pc-2,n))
def ld_a(v):emit(0x3e,v)
def out(port):emit(0xd3,port)
def vaddr(address):
 ld_a(address&255);out(0xbf);ld_a(0x40|(address>>8));out(0xbf)
def reg(index,value):
 ld_a(value);out(0xbf);ld_a(0x80|index);out(0xbf)
def data(label_name,count):
 emit(0x21,0,0);refs.append((pc-2,label_name));emit(0x01,count&255,count>>8)
 label('copy_'+label_name);emit(0x7e);out(0xbe);emit(0x23,0x0b,0x78,0xb1);jump(0xc2,'copy_'+label_name)
rom[0:3]=bytes([0xc3,0,1])
# Pause NMI toggles a RAM flag. VDP is touched only by the main loop.
rom[0x66:0x72]=bytes([0xf5,0x3a,0,0xc0,0xee,0x30,0x32,0,0xc0,0xf1,0xed,0x45])
emit(0xf3,0x31,0xf0,0xdf,0xaf,0x32,0,0xc0)
reg(1,0);reg(0,4);reg(2,0x0e);reg(3,0xff);reg(4,7);reg(5,0x7e);reg(6,0);reg(7,0);reg(8,0);reg(9,0);reg(10,0xff)
vaddr(0);emit(0x01,0,0x40);label('clear');emit(0xaf);out(0xbe);emit(0x0b,0x78,0xb1);jump(0xc2,'clear')
vaddr(0);data('font',4096)
vaddr(0x3800);data('screen',1536)
ld_a(0);out(0xbf);ld_a(0xc0);out(0xbf)
for i in range(32):ld_a(0x3f if i==1 else 3 if i==0 else 0);out(0xbe)
# Terminate sprite list and enable the display.
vaddr(0x3f00);ld_a(0xd0);out(0xbe);reg(1,0x40)
for b in [0x80,0x19,0x9f,0xbf,0xdf,0xff]:ld_a(b);out(0x7f)
label('frame');emit(0xdb,0xbf,0xe6,0x80);jump(0xca,'frame')
emit(0xdb,0xdc,0x47,0x3a,0,0xc0,0xa8,0xee,0x3c,0xe6,0x3f,0x4f)
ld_a(0);out(0xbf);ld_a(0xc0);out(0xbf);emit(0x79);out(0xbe)
emit(0x78,0xe6,0x10);jump(0xc2,'mute');ld_a(0x90);jump(0xc3,'sound')
label('mute');ld_a(0x9f);label('sound');out(0x7f);jump(0xc3,'frame')
glyphs={
 'A':[14,17,17,31,17,17,17],'B':[30,17,17,30,17,17,30],
 'C':[14,17,16,16,16,17,14],'D':[30,17,17,17,17,17,30],
 'E':[31,16,16,30,16,16,31],'F':[31,16,16,30,16,16,16],
 'G':[14,17,16,23,17,17,15],'H':[17,17,17,31,17,17,17],
 'I':[14,4,4,4,4,4,14],'K':[17,18,20,24,20,18,17],
 'L':[16,16,16,16,16,16,31],'M':[17,27,21,21,17,17,17],
 'N':[17,25,21,19,17,17,17],'O':[14,17,17,17,17,17,14],
 'P':[30,17,17,30,16,16,16],'R':[30,17,17,30,20,18,17],
 'S':[15,16,16,14,1,1,30],'T':[31,4,4,4,4,4,4],
 'U':[17,17,17,17,17,17,14],'W':[17,17,17,21,21,21,10],
 'Y':[17,17,10,4,4,4,4], ' ':[0]*7,
}
label('font')
font=bytearray(4096)
for ch,rows in glyphs.items():
 for y,bits in enumerate(rows):font[ord(ch)*32+y*4]=bits<<2
emit(*font)
label('screen');screen=bytearray(1536)
for row,text in [(3,'NANOBLAST SMS TEST'),(6,'PICTURE OK'),(10,'PRESS D PAD OR BUTTONS'),(13,'BACKGROUND SHOULD CHANGE'),(16,'BUTTON B SHOULD PLAY A TONE'),(19,'START CHANGES THE BACKGROUND')]:
 assert len(text)<=32 and all(c in glyphs for c in text)
 for col,ch in enumerate(text,(32-len(text))//2):screen[(row*32+col)*2]=ord(ch)
emit(*screen)
for addr,name in refs:rom[addr:addr+2]=labels[name].to_bytes(2,'little')
assert pc<0x1ff0
rom[0x1ff0:0x1ff8]=b'TMR SEGA';rom[0x1fff]=0x4a
checksum=sum(rom[:0x1ff0])&0xffff;rom[0x1ffa:0x1ffc]=checksum.to_bytes(2,'little')
out=root.parent.parent/'outputs/sms-integration-fixes';out.mkdir(parents=True,exist_ok=True)
(out/'NANOBLAST-Test.sms').write_bytes(rom)
(root/'ui/sms_test_rom.inc').write_text('// Original NANOBLAST SMS diagnostic, generated by scripts/make_sms_test_rom.py.\nstatic const uint8_t sms_test_rom[]={\n'+''.join(' '+','.join('0x%02x'%b for b in rom[i:i+24])+',\n' for i in range(0,len(rom),24))+'};\n')
print('SMS test ROM:',len(rom),'bytes; SHA256',hashlib.sha256(rom).hexdigest())
